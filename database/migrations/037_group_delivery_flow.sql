--  v5.13.0 — روند تحویل تسک گروهی: گروهِ دارای سرگروه همیشه با تیک سرگروه، بدون سرگروه با تیک همه‌ی اعضا.
--  ستون tasks.group_head_approval از این نسخه فقط آینه‌ی «گروه سرگروه دارد» است؛ تسک‌های باز یک بار هماهنگ می‌شوند.
--  اگر اجرا نشود، برنامه یک بار خودش آن را اجرا می‌کند (SCHEMA_AUTO).
-- ============================================================================
UPDATE tasks t JOIN project_groups g ON g.id = t.assignee_group_id
SET t.group_head_approval = IF(g.head_id IS NULL, 0, 1)
WHERE t.is_completed = 0;
