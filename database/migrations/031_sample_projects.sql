-- ============================================================================
--  v4.5.1 — علامت «پروژه‌ی نمونه»ای که سیستم هنگام ثبت‌نام برای کاربر می‌سازد (ProjectService::createSample)
--  تا در فهرست‌ها و آمار پنل مدیر شمرده نشود. با تغییر عنوان توسط کاربر، علامت برداشته می‌شود.
--  پروژه‌های نمونه‌ی قبلی (عنوان و توضیح پیش‌فرض، دست‌نخورده) علامت می‌خورند.
--  اگر اجرا نشود، برنامه یک بار خودش آن را اجرا می‌کند (SCHEMA_AUTO).
-- ============================================================================
ALTER TABLE `projects` ADD COLUMN `is_sample` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '1 = پروژه‌ی نمونه‌ی خودکار ثبت‌نام (در پنل مدیر شمرده نمی‌شود)' AFTER `status`;

UPDATE `projects` SET `is_sample` = 1 WHERE `title` = 'پروژه نمونه' AND `description` LIKE 'این یک پروژه‌ی نمونه است تا تسک‌های اولیه‌ات را با آن ثبت کنی%';
