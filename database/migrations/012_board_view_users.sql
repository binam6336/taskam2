--  هر عضو پیش‌فرض فقط تسک‌های خودش را در برد می‌بیند؛ اعضایی که این‌جا انتخاب شوند
--  (JSON آرایه‌ی شناسه‌ی کاربر) تسک‌هایشان (بر اساس مسئول) هم در برد او دیده می‌شود.
--  دسترسی منسوخ «view» در board_permissions دیگر استفاده نمی‌شود.
--  اگر اجرا نشود، برنامه در اولین استفاده (در صورت داشتن مجوز ALTER) خودش آن را اضافه می‌کند.
-- ============================================================================
ALTER TABLE `project_members`
  ADD COLUMN `board_view_users` TEXT NULL DEFAULT NULL
    COMMENT 'JSON: شناسه‌ی اعضایی که تسک‌هایشان در برد این عضو دیده می‌شود'
    AFTER `board_permissions`;
