  ADD COLUMN `attempts` TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'تعداد تلاش‌های ناموفق قبلی (تلاش مجدد خودکار، حداکثر ۲)' AFTER `tokens`,
  ADD COLUMN `retry_at` TIMESTAMP NULL DEFAULT NULL COMMENT 'زمان تلاش مجدد بعدی (NULL = بدون انتظار)' AFTER `attempts`;
