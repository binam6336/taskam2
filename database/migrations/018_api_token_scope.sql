-- ============================================================================
--  سطح دسترسی توکن‌های API (v3.26.0): read = فقط درخواست‌های خواندنی (GET)، write = خواندن و نوشتن
--  توکن‌های قبلی write می‌مانند تا برنامه‌های فعلی از کار نیفتند.
--  اگر اجرا نشود، برنامه در اولین استفاده (در صورت داشتن مجوز ALTER) خودش آن را اضافه می‌کند.
-- ============================================================================
ALTER TABLE `api_tokens`
  ADD COLUMN `scope` ENUM('read','write') NOT NULL DEFAULT 'write' COMMENT 'read = فقط خواندن' AFTER `token_prefix`;
